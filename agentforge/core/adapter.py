_ADAPTER_REGISTRY: Dict[str, type[BaseAgentAdapter]] = {
    "langchain": LangChainAdapter,
    "llamaindex": LlamaIndexAdapter,
    "llama-index": LlamaIndexAdapter,
    "google-genai": GoogleGenAIAdapter,
    "googlegenai": GoogleGenAIAdapter,
    "gemini": GoogleGenAIAdapter,
    "adk": GoogleGenAIAdapter,
    "crewai": CrewAIAdapter,
    "autogen": AutoGenAdapter,
    "langgraph": LangGraphAdapter,
    "deepagent": DeepAgentAdapter,
    "bedrock": BedrockAdapter,
    "aws-bedrock": BedrockAdapter,
}


def get_adapter(framework: str, config: Optional[Dict[str, Any]] = None) -> BaseAgentAdapter:
    """
    Factory resolving and instantiating an adapter by framework name.
    Supports canonical names, abbreviations (e.g. 'adk'), and kebab/snake variants.
    """
    normalized_name = framework.strip().lower()
    adapter_cls = _ADAPTER_REGISTRY.get(normalized_name)
    if not adapter_cls:
        # Fallback for underscore/hyphen interchangeability
        adapter_cls = _ADAPTER_REGISTRY.get(normalized_name.replace("_", "-"))
    if not adapter_cls:
        # Fallback for hyphen/underscore interchangeability
        adapter_cls = _ADAPTER_REGISTRY.get(normalized_name.replace("-", "_"))
    if not adapter_cls:
        raise ValueError(
            f"Unsupported agent framework: '{framework}'. "
            f"Supported frameworks: {sorted(list(_ADAPTER_REGISTRY.keys()))}"
        )
    return adapter_cls(config=config)
