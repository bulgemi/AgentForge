# 2. Exception Hierarchy
# ============================================================================

class AdapterError(Exception):
    """Base exception for all adapter-related failures."""
    pass


class AdapterConfigurationError(AdapterError):
    """Raised when adapter configuration or credentials are missing or invalid."""
    pass


class AdapterExecutionError(AdapterError):
    """Raised when an underlying framework or model execution fails."""
    pass


class InvalidInputError(AdapterError):
    """Raised when agent input is missing or malformed."""
    pass


class InterruptRequiredError(AdapterError):
    """Raised when an execution triggers a human approval requirement."""
    def __init__(self, message: str, interrupt_id: str, payload: Optional[Dict[str, Any]] = None):
        super().__init__(message)
        self.interrupt_id = interrupt_id
        self.payload = payload or {}


class AdapterTimeoutError(AdapterError):
    """Raised when adapter invocation exceeds the allowed deadline."""
    pass


