class AgentEventType(str, Enum):
    """Normalized event types for real-time agent streaming."""
    TOKEN = "token"          # Incremental text token
    EVIDENCE = "evidence"    # Grounding, citations, tool outputs, retrieved documents
    META = "meta"            # Metadata (model name, latency, token usage, thought traces)
    INTERRUPT = "interrupt"  # Human-in-the-loop (HITL) approval pause gate
    ERROR = "error"          # Runtime, upstream, or validation error
    DONE = "done"            # Stream completion terminal indicator


class AgentRole(str, Enum):
    """Normalized participant roles in agent conversations."""
    SYSTEM = "system"
    USER = "user"
    ASSISTANT = "assistant"
    TOOL = "tool"
    FUNCTION = "function"


class ToolDefinition(BaseModel):
    """Normalized tool specification schema."""
    name: str
    description: str
    parameters: Dict[str, Any] = Field(default_factory=dict)

    model_config = ConfigDict(populate_by_name=True, from_attributes=True)

    def to_dict(self) -> Dict[str, Any]:
        if hasattr(self, "model_dump"):
            return self.model_dump()
        return self.dict()


class ToolCall(BaseModel):
    """Normalized tool call request generated by an agent."""
    id: str = Field(default_factory=lambda: str(uuid.uuid4()))
    name: str
    arguments: Dict[str, Any] = Field(default_factory=dict)

    model_config = ConfigDict(populate_by_name=True, from_attributes=True)

    def to_dict(self) -> Dict[str, Any]:
        if hasattr(self, "model_dump"):
            return self.model_dump()
        return self.dict()


class ToolResult(BaseModel):
    """Normalized execution result of a tool call."""
    tool_call_id: str
    name: str
    content: str
    is_error: bool = False

    model_config = ConfigDict(populate_by_name=True, from_attributes=True)

    def to_dict(self) -> Dict[str, Any]:
        if hasattr(self, "model_dump"):
            return self.model_dump()
        return self.dict()


class AgentMessage(BaseModel):
    """Normalized conversation message representation."""
    role: AgentRole = AgentRole.USER
    content: str = ""
    name: Optional[str] = None
    tool_call_id: Optional[str] = None
    tool_calls: Optional[List[Dict[str, Any]]] = None
    metadata: Dict[str, Any] = Field(default_factory=dict)

    model_config = ConfigDict(populate_by_name=True, from_attributes=True)

    def to_dict(self) -> Dict[str, Any]:
        res = self.model_dump() if hasattr(self, "model_dump") else self.dict()
        res["role"] = self.role.value if isinstance(self.role, Enum) else str(self.role)
        return res


class AgentInput(BaseModel):
    """Standardized input payload passed to BaseAgentAdapter."""
    prompt: Optional[str] = None
    messages: List[AgentMessage] = Field(default_factory=list)
    session_id: Optional[str] = None
    chat_id: Optional[str] = None
    turn_id: Optional[str] = None
    tools: Optional[List[ToolDefinition]] = None
    config: Dict[str, Any] = Field(default_factory=dict)
    resume_payload: Optional[Dict[str, Any]] = None

    model_config = ConfigDict(populate_by_name=True, from_attributes=True)

    def get_prompt_or_last_message(self) -> str:
        """Extract prompt text or fallback to the latest user message content."""
        if self.prompt is not None and self.prompt.strip():
            return self.prompt.strip()
        for msg in reversed(self.messages):
            if (msg.role == AgentRole.USER or str(msg.role) == "user") and msg.content and msg.content.strip():
                return msg.content.strip()
        return ""


class AgentOutput(BaseModel):
    """Standardized output payload returned by BaseAgentAdapter.ainvoke."""
    content: str = ""
    messages: List[AgentMessage] = Field(default_factory=list)
    tool_calls: List[ToolCall] = Field(default_factory=list)
    metadata: Dict[str, Any] = Field(default_factory=dict)
    turn_id: Optional[str] = None
    finish_reason: Optional[str] = None

    model_config = ConfigDict(populate_by_name=True, from_attributes=True)

    def to_dict(self) -> Dict[str, Any]:
        if hasattr(self, "model_dump"):
            return self.model_dump()
        return self.dict()


class AgentChunk(BaseModel):
    """
    Standardized stream chunk yielded during real-time streaming.
    Supports both `event` and `type` property access for complete contract compatibility.
    """
    event: AgentEventType = AgentEventType.TOKEN
    data: Union[Dict[str, Any], str, None] = None
    content: Optional[str] = None
    metadata: Dict[str, Any] = Field(default_factory=dict)
    error: Optional[str] = None
    timestamp: str = Field(default_factory=lambda: datetime.now(timezone.utc).isoformat())
    id: Optional[str] = None

    model_config = ConfigDict(populate_by_name=True, from_attributes=True)

    def __init__(self, **data_kw: Any) -> None:
        # Support initializing with 'type' as alias for 'event'
        if "type" in data_kw and "event" not in data_kw:
            data_kw["event"] = data_kw.pop("type")
        super().__init__(**data_kw)

    @property
    def type(self) -> AgentEventType:
        """Alias for event type compatibility."""
        return self.event

    def to_dict(self) -> Dict[str, Any]:
        """Pydantic v1 / v2 compatible dictionary serialization."""
        res = self.model_dump() if hasattr(self, "model_dump") else self.dict()
        event_str = self.event.value if isinstance(self.event, Enum) else str(self.event)
        res["event"] = event_str
        res["type"] = event_str
        return res

    def to_json(self) -> str:
        """Serialize chunk to a valid JSON string with fallback for non-serializable objects."""
        return json.dumps(self.to_dict(), default=str)

    def to_sse_event(self) -> str:
        """Format chunk directly into an SSE wire event."""
        event_name = self.event.value if isinstance(self.event, Enum) else str(self.event)
        payload: Dict[str, Any] = {
            "type": event_name,
            "content": self.content if self.content is not None else (self.data if isinstance(self.data, str) else None),
            "data": self.data,
            "metadata": self.metadata,
            "timestamp": self.timestamp,
        }
        if self.error:
            payload["error"] = self.error
        if self.id:
            payload["id"] = self.id

        data_json = json.dumps(payload, default=str)
        lines = [f"event: {event_name}", f"data: {data_json}"]
        if self.id:
            lines.append(f"id: {self.id}")
        return "\n".join(lines) + "\n\n"


