class LangChainAdapter(BaseAgentAdapter):
    """Adapter for LangChain LCEL chains and Runnable agent executors."""

    async def ainvoke(self, input_data: AgentInput, context: Optional[Any] = None) -> AgentOutput:
        prompt = input_data.get_prompt_or_last_message()
        if not prompt:
            raise InvalidInputError("Prompt or user message cannot be empty")

        runnable = self.config.get("runnable")
        if runnable and hasattr(runnable, "ainvoke"):
            try:
                res = await runnable.ainvoke({"input": prompt})
                content = getattr(res, "content", str(res))
                return AgentOutput(content=content, turn_id=input_data.turn_id, finish_reason="stop")
            except Exception as e:
                raise AdapterExecutionError(f"LangChain execution error: {e}") from e

        return AgentOutput(
            content=f"[LangChain] Processed: {prompt}",
            turn_id=input_data.turn_id,
            finish_reason="stop",
            metadata={"framework": "langchain"},
        )

    async def astream(self, input_data: AgentInput, context: Optional[Any] = None) -> AsyncGenerator[AgentChunk, None]:
        prompt = input_data.get_prompt_or_last_message()
        if not prompt:
            raise InvalidInputError("Prompt or user message cannot be empty")

        runnable = self.config.get("runnable")
        if runnable and hasattr(runnable, "astream"):
            try:
                async for chunk in runnable.astream({"input": prompt}):
                    token = getattr(chunk, "content", str(chunk))
                    yield AgentChunk(event=AgentEventType.TOKEN, data=token, content=token)
                yield AgentChunk(event=AgentEventType.DONE, data={"finish_reason": "stop"})
                return
            except Exception as e:
                yield AgentChunk(event=AgentEventType.ERROR, error=str(e), data={"exception": type(e).__name__})
                return

        if "interrupt" in prompt.lower():
            interrupt_id = "lc-int-" + uuid.uuid4().hex[:8]
            yield AgentChunk(
                event=AgentEventType.INTERRUPT,
                data={"action": "approve_action", "details": "Approval required for operation"},
                id=interrupt_id,
            )
            return

        tokens = ["[LangChain] ", "Response ", "to ", f"'{prompt}'"]
        for token in tokens:
            await asyncio.sleep(0.005)
            yield AgentChunk(event=AgentEventType.TOKEN, data=token, content=token)
        yield AgentChunk(event=AgentEventType.DONE, data={"finish_reason": "stop"})

    async def ahandle_interrupt(
        self,
        interrupt_id: str,
        decision: str,
        state_update: Optional[Dict[str, Any]] = None,
        context: Optional[Any] = None,
    ) -> AgentOutput:
        return AgentOutput(
            content=f"[LangChain] Interrupt {interrupt_id} resolved with decision: {decision}",
            metadata={"decision": decision, "state_update": state_update or {}},
            finish_reason="resolved",
        )


