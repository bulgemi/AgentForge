# 3. Base Agent Adapter Abstract Interface
# ============================================================================

class BaseAgentAdapter(ABC):
    """
    Universal abstraction interface for all AI agent framework integrations in AgentForge.
    All concrete adapters must inherit from this class.
    """

    def __init__(self, config: Optional[Dict[str, Any]] = None, **kwargs: Any) -> None:
        self.config: Dict[str, Any] = config or {}
        if kwargs:
            self.config.update(kwargs)
        self._is_initialized: bool = False

    async def initialize(self) -> None:
        """Hook for lazy loading models, clients, and tool bindings."""
        self._is_initialized = True

    @abstractmethod
    async def ainvoke(
        self,
        input_data: AgentInput,
        context: Optional[Any] = None,
    ) -> AgentOutput:
        """Execute a non-streaming single-turn agent call."""
        pass

    @abstractmethod
    async def astream(
        self,
        input_data: AgentInput,
        context: Optional[Any] = None,
    ) -> AsyncGenerator[AgentChunk, None]:
        """Stream normalized AgentChunk events in real-time."""
        pass

    @abstractmethod
    async def ahandle_interrupt(
        self,
        interrupt_id: str,
        decision: str,
        state_update: Optional[Dict[str, Any]] = None,
        context: Optional[Any] = None,
    ) -> Union[AgentOutput, AsyncGenerator[AgentChunk, None]]:
        """Handle resolution and resumption of a suspended HITL interrupt."""
        pass

    async def health_check(self) -> bool:
        """Check operational status of model connections and credentials."""
        return True


